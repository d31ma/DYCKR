pub fn is_framework_marker(name: &str) -> bool {
    if name == "allow" {
        return false;
    }
    let name = name
        .strip_prefix("yon::")
        .or_else(|| name.strip_prefix("tac::"))
        .unwrap_or(name);
    let normalized = name.replace('_', "").to_ascii_lowercase();
    framework_marker_names().any(|marker| marker.to_ascii_lowercase() == normalized)
}

